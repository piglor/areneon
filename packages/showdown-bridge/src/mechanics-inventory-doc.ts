// Renders docs/mechanics-inventory.md from the golden inventory and the committed
// weights report (#1465). The document is generated like docs/mechanics-parity.md:
// edit the inputs or this renderer, never the file; a test compares the committed
// text with a fresh render.

import { fileURLToPath } from "node:url";
import { type Kind, type MechanicsInventory } from "./mechanics-inventory.ts";
import { buildIndex, entitiesFor, type WeightsReport } from "./mechanics-inventory-weights.ts";

export const INVENTORY_DOC = fileURLToPath(new URL("../../../docs/mechanics-inventory.md", import.meta.url));

/** Parts per million as a percentage with two decimals, in integers. */
export const percent = (ppm: number): string => `${Math.floor(ppm / 10_000)}.${String(Math.floor((ppm % 10_000) / 100)).padStart(2, "0")}%`;
const cmp = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);
const row = (cells: (string | number)[]): string => `| ${cells.join(" | ")} |`;
const table = (head: string[], rows: (string | number)[][]): string[] => [row(head), row(head.map(() => "---")), ...rows.map(row)];

const SHARES = [500_000, 750_000, 900_000, 950_000, 990_000, 1_000_000];
const STEPS = [5, 10, 25, 50, 100];

export function renderInventoryDoc(inv: MechanicsInventory, weights: WeightsReport): string {
  const index = buildIndex(inv);
  const lists: Record<Kind, typeof inv.moves> = { move: inv.moves, ability: inv.abilities, item: inv.items, condition: inv.conditions };
  const own = (e: (typeof inv.moves)[number]): boolean => e.defined_in === undefined || e.defined_in === "table";
  const out: string[] = [
    "# Mechanics coverage inventory",
    "",
    "Generated by `node packages/showdown-bridge/scripts/mechanics-inventory.ts` from `fixtures/showdown/<format>/mechanics-inventory.json` and its weights report; a test compares this file with a fresh render, so edit the inputs or the renderer, never this file (#1465, ADR-030 groundwork G5).",
    "",
    `Format \`${inv.format_id}\` (mod \`${inv.mod}\`), Showdown pin \`${inv.showdown_commit.slice(0, 8)}\`. Inventory format \`${inv.inventory_format}\`.`,
    "",
    "Every id and handler below is read from the pinned engine's data for the format's mod by reflection; nothing is a hand list. The weights are the committed `fixtures-v1` dev split (never validation) and the Smogon usage weight table (aggregate public data, ADR-020). Run-Episode weights are counts printed by the script and journaled on the ticket, never committed.",
    "",
    "## How many damage-relevant handlers the roster reaches",
    "",
    `ADR-030 counted 382 damage-relevant handler definitions with an unfiltered \`grep\` of the base data files and could not say how many the roster reaches. The reflective count over every entry of the mod (roster or not) and the count over the roster-reachable entities are:`,
    "",
    ...table(
      ["Kind", "Roster entries", "With handlers", "With damage handlers", "Damage handler definitions reached", "Same count over every entry of the mod"],
      (["move", "ability", "item", "condition"] as const).map((kind) => {
        const list = lists[kind];
        const unfiltered = inv.unfiltered[`${kind === "ability" ? "abilitie" : kind}s` as "moves"];
        return [kind === "condition" ? "conditions" : kind === "ability" ? "abilities" : `${kind}s`, list.length, list.filter((e) => e.handlers.length > 0).length, list.filter((e) => e.damage_handlers.length > 0).length, list.filter(own).reduce((n, e) => n + e.damage_handlers.length, 0), unfiltered];
      }),
    ),
    "",
  ];
  const reached = (["move", "ability", "item", "condition"] as const).reduce((n, kind) => n + lists[kind].filter(own).reduce((m, e) => m + e.damage_handlers.length, 0), 0);
  const all = Object.values(inv.unfiltered).reduce((n, v) => n + v, 0);
  out.push(
    `**The roster reaches ${reached} of the ${all} damage-relevant handler definitions of the mod (${index.damage.size} entities carry them).** Conditions defined in a move, ability or item are that entity's own handlers (their definitions are counted in its row), so the \`conditions\` row counts only the mod's condition table; the ADR's 382 was a text count of the base data files, so the two numbers differ by method, not by a filter alone.`,
    "",
    "## Damage handler names",
    "",
    ...table(
      ["Handler", "Definitions reached", "Entities"],
      inv.damage_handler_names.map((name) => {
        const holders = (["move", "ability", "item", "condition"] as const).flatMap((kind) => lists[kind].filter((e) => own(e) && e.damage_handlers.some((h) => h.slice(h.lastIndexOf(".") + 1) === name)));
        return [`\`${name}\``, holders.reduce((n, e) => n + e.damage_handlers.filter((h) => h.slice(h.lastIndexOf(".") + 1) === name).length, 0), holders.length];
      }),
    ),
    "",
    "## What a build order covers",
    "",
    `A backend that implements the top N damage-relevant entities covers a team when every such entity of the team is among them. Dataset: ${weights.dataset.teams} teams of \`${weights.dataset.id}\` (dev split). Two teams make a game, so the share of games is about the square of the share of teams. The usage column is an independence estimate (each entity held by a team with the probability the usage table gives it, entities independent); it has no teams to count.`,
    "",
    ...table(
      ["Teams covered", "Entities (dataset)", "Handler names (dataset)", "Entities (usage estimate)"],
      SHARES.map((share) => [percent(share), entitiesFor(weights.coverage.teams, share) ?? "never", entitiesFor(weights.coverage.handler_names, share) ?? "never", entitiesFor(weights.coverage.usage_independence, share) ?? "never"]),
    ),
    "",
    ...table(
      ["Top N entities", "Teams covered", "Games covered (about)", "Usage estimate (teams)"],
      STEPS.filter((n) => n < weights.coverage.teams.order.length).map((n) => {
        const teams = weights.coverage.teams.covered_ppm[n] as number;
        return [n, percent(teams), percent(Math.floor((teams * teams) / 1_000_000)), percent(weights.coverage.usage_independence.covered_ppm[n] as number)];
      }),
    ),
    "",
    `The order has ${weights.coverage.teams.order.length} damage-relevant entities held by at least one dataset team and ${weights.damage.length} in the roster.`,
    "",
    "## Top entities by dataset teams",
    "",
    ...table(
      ["Rank", "Entity", "Damage handlers", "Dataset teams", "Usage (slot share)"],
      weights.coverage.teams.order.slice(0, 30).map((e, n) => {
        const w = weights.weights.find((x) => x.key === e.key);
        return [n + 1, `\`${e.key}\``, (index.damage.get(e.key) ?? []).join(", "), e.count, percent(w?.usage_slot_ppm ?? 0)];
      }),
    ),
    "",
    "## Entities grouped by handler set",
    "",
    "Entities with the same set of damage handler names need the same engine branches; the most common sets, with the dataset teams holding at least one of the group:",
    "",
  );
  const groups = new Map<string, { entities: string[]; teams: number }>();
  for (const [key, names] of index.damage) {
    const group = groups.get(names.join(", ")) ?? { entities: [], teams: 0 };
    group.entities.push(key);
    group.teams += weights.weights.find((w) => w.key === key)?.teams ?? 0;
    groups.set(names.join(", "), group);
  }
  out.push(
    ...table(
      ["Handler set", "Entities", "Sum of dataset team counts"],
      [...groups].sort((a, b) => b[1].entities.length - a[1].entities.length || cmp(a[0], b[0])).slice(0, 15).map(([names, g]) => [names, g.entities.length, g.teams]),
    ),
    "",
    "## Simulation-code references",
    "",
    "Ids the engine's simulation code tests directly (`hasAbility`, `.id ===`, a switch on an effect id, ...), scanned from `sim/*.ts` and the mod chain's `scripts.ts` and `conditions.ts`. An effect implemented there has no handler to find:",
    "",
    ...table(
      ["Entity", "References"],
      (["move", "ability", "item", "condition"] as const).flatMap((kind) => lists[kind].filter((e) => e.sim_refs.length > 0).map((e) => [`\`${kind}:${e.id}\``, e.sim_refs.join("; ")])),
    ),
    "",
    "## Pairs",
    "",
    `Pairs of damage-relevant moves, abilities and items (${weights.pairs.entities} entities, ${weights.pairs.independent_pairs} pairs): ${weights.pairs.pairs_seen} pairs are held together by at least one of the ${weights.pairs.teams} dataset teams, and ${weights.pairs.independent_ge_1e4} reach 10^-4 under the independence estimate of the usage table (ADR-028 section 5's input). The most frequent dataset pairs:`,
    "",
    ...table(
      ["Entity", "Entity", "Dataset teams"],
      weights.pairs.top.slice(0, 15).map((p) => [`\`${p.a}\``, `\`${p.b}\``, p.teams]),
    ),
    "",
    "## Limits",
    "",
    "- A literal is found only when it is written as a string in one of the scan patterns; an id held in a variable is not. A handler body is read from the function's source text, so a start made through a helper is not seen.",
    `- ${inv.unresolved_starts.length} start${inv.unresolved_starts.length === 1 ? "" : "s"} name a condition the engine has no condition for${inv.unresolved_starts.length > 0 ? `: ${inv.unresolved_starts.map((s) => `\`${s}\``).join(", ")}` : ""}.`,
    "- Conditions no roster entity starts keep an empty `started_by`; the engine may still start them from simulation code (see the references above).",
    "- The dataset is small (the committed dev split), so shares have coarse resolution; the usage estimate is independence-based and stated as such. Re-run after the Regulation M-D pin bump and read the diff against this baseline (#1103).",
    "",
  );
  return out.join("\n");
}
