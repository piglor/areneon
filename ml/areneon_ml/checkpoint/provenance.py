"""The C1/C6 checker (protocol `docs/research/evaluation-protocol.md`, C1-C3, C5-C7).

It computes, from CheckpointRecords alone and never by hand, whether an
opponent is **seen** or **held out** relative to a candidate (C1), and
whether two checkpoints are **independent** (C6).

The provenance graph has checkpoints and data sources as nodes. A record adds
an edge from its checkpoint to its ``parent`` ("initialised from"), to each
``league_opponents`` entry and to its ``exploiter_target`` ("trained
against"), and to each of its ``training_set_hashes`` ("trained on"). A
training set is a data-source node; the ``sources`` registry says which
checkpoints generated it (an empty list: a behaviour-cloning or fine-tuning
source made outside the learned lineage), and the node has an edge to each of
them ("trained on data generated by"). The **ancestry** of a checkpoint is the
checkpoint itself plus every node reachable from it, transitively, as recorded
when it was frozen. Scripted baselines and the shared training team pool are
not nodes (C6).

Fail closed: a referenced checkpoint without a record (a checkpoint without a
record cannot enter an evaluation pool, C7), a training set missing from the
registry, a repeated record, a cycle, or an evaluation exploiter that was in
its own target's league (C3) is a ``ProvenanceError``, never a classification.

Classification of an opponent relative to a candidate (each a Preview and
Battle pair, or one checkpoint):

* a scripted baseline is **seen** (C5);
* **seen** when an opponent checkpoint is in the candidate's ancestry;
* **held out** when an opponent is an evaluation exploiter of the candidate
  (it was trained after the candidate was frozen; the candidate never trained
  against it, C2/C3);
* **held out** when the two ancestries are independent (C6);
* otherwise **seen**: a related lineage (they share a learned checkpoint or a
  data source).
"""

from __future__ import annotations

import re
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass

from areneon_ml.checkpoint.record import CheckpointRecord

_HASH = re.compile(r"[0-9a-f]{64}")
_BASELINE = re.compile(r"[a-z0-9][a-z0-9._-]*@[A-Za-z0-9._-]+")
SEEN = "seen"
HELD_OUT = "held_out"


class ProvenanceError(ValueError):
    """The records cannot support a classification."""


@dataclass(frozen=True)
class Ancestry:
    """Learned checkpoints (the checkpoint itself included) and data sources behind a checkpoint."""

    checkpoints: frozenset[str]
    sources: frozenset[str]


@dataclass(frozen=True)
class Independence:
    independent: bool
    shared_checkpoints: tuple[str, ...]
    shared_sources: tuple[str, ...]


@dataclass(frozen=True)
class Classification:
    label: str
    reason: str


def _is_hash(value: str) -> bool:
    return _HASH.fullmatch(value) is not None


class ProvenanceGraph:
    """The records of a set of checkpoints and the registry of their training sets."""

    def __init__(
        self, records: Iterable[CheckpointRecord], sources: Mapping[str, Sequence[str]]
    ) -> None:
        self._records: dict[str, CheckpointRecord] = {}
        for record in records:
            if record.checkpoint_id in self._records:
                raise ProvenanceError(f"checkpoint {record.checkpoint_id} has two records")
            self._records[record.checkpoint_id] = record
        self._sources = {key: tuple(value) for key, value in sources.items()}
        self._check_registry()
        self._check_references()
        self._check_exploiters()
        self._ancestry: dict[str, Ancestry] = {}
        self._resolve_all()

    # -- construction checks -------------------------------------------------

    def _check_registry(self) -> None:
        for key, generators in self._sources.items():
            if not _is_hash(key):
                raise ProvenanceError(f"data source {key!r} is not a SHA-256 hash")
            if list(generators) != sorted(set(generators)) or not all(map(_is_hash, generators)):
                raise ProvenanceError(
                    f"data source {key}: its generators must be sorted unique ids"
                )

    def _require(self, checkpoint: str, why: str) -> None:
        if checkpoint not in self._records:
            raise ProvenanceError(f"checkpoint {checkpoint} ({why}) has no record")

    def _check_references(self) -> None:
        for record in self._records.values():
            who = record.checkpoint_id
            if record.parent is not None:
                self._require(record.parent, f"parent of {who}")
            for opponent in record.league_opponents:
                self._require(opponent, f"league opponent of {who}")
            if record.exploiter_target is not None:
                self._require(record.exploiter_target, f"exploiter target of {who}")
            for training_set in record.training_set_hashes:
                if training_set not in self._sources:
                    raise ProvenanceError(
                        f"training set {training_set} (of {who}) is not in the sources registry"
                    )
        for source, generators in self._sources.items():
            for generator in generators:
                self._require(generator, f"generator of data source {source}")

    def _check_exploiters(self) -> None:
        """C3: an evaluation exploiter is never in the league of the candidate it targets."""
        for record in self._records.values():
            for opponent in record.league_opponents:
                if self._records[opponent].exploiter_target == record.checkpoint_id:
                    raise ProvenanceError(
                        f"C3: {opponent} is an evaluation exploiter of {record.checkpoint_id} "
                        "and sits in its league"
                    )

    def _edges(self, checkpoint: str) -> list[str]:
        """The checkpoints this one was initialised from, trained against, or learned from."""
        record = self._records[checkpoint]
        found = [record.parent, *record.league_opponents, record.exploiter_target]
        for training_set in record.training_set_hashes:
            found.extend(self._sources[training_set])
        return [edge for edge in found if edge is not None]

    def _resolve_all(self) -> None:
        """Every ancestry, by an iterative depth-first walk (a lineage can be long)."""
        visiting: set[str] = set()
        for root in sorted(self._records):
            stack = [(root, self._edges(root), 0)]
            while stack:
                checkpoint, edges, position = stack.pop()
                if position == 0:
                    if checkpoint in self._ancestry:
                        continue  # a root already resolved below an earlier root
                    visiting.add(checkpoint)
                if position < len(edges):
                    stack.append((checkpoint, edges, position + 1))
                    child = edges[position]
                    if child in visiting:
                        raise ProvenanceError(f"the provenance graph has a cycle through {child}")
                    if child not in self._ancestry:
                        stack.append((child, self._edges(child), 0))
                    continue
                visiting.discard(checkpoint)
                record = self._records[checkpoint]
                checkpoints = {checkpoint}
                sources = set(record.training_set_hashes)
                for edge in edges:
                    checkpoints |= self._ancestry[edge].checkpoints
                    sources |= self._ancestry[edge].sources
                self._ancestry[checkpoint] = Ancestry(frozenset(checkpoints), frozenset(sources))

    # -- queries -------------------------------------------------------------

    def ancestry(self, checkpoints: str | Sequence[str]) -> Ancestry:
        """The union of the ancestries of one checkpoint or of a pair."""
        ids = [checkpoints] if isinstance(checkpoints, str) else list(checkpoints)
        if not ids:
            raise ProvenanceError("no checkpoint given")
        for checkpoint in ids:
            self._require(checkpoint, "asked about")
        return Ancestry(
            frozenset().union(*(self._ancestry[c].checkpoints for c in ids)),
            frozenset().union(*(self._ancestry[c].sources for c in ids)),
        )

    def independent(self, a: str | Sequence[str], b: str | Sequence[str]) -> Independence:
        """C6: independent only if the ancestries share no learned checkpoint and no data source."""
        first, second = self.ancestry(a), self.ancestry(b)
        checkpoints = tuple(sorted(first.checkpoints & second.checkpoints))
        sources = tuple(sorted(first.sources & second.sources))
        return Independence(not checkpoints and not sources, checkpoints, sources)

    def classify(
        self, candidate: str | Sequence[str], opponent: str | Sequence[str]
    ) -> Classification:
        """C1: whether ``opponent`` is seen or held out relative to ``candidate``.

        ``opponent`` is a scripted baseline name (``<name>@<commit>``), a
        checkpoint id or a pair of ids.
        """
        mine = self.ancestry(candidate)
        if isinstance(opponent, str) and not _is_hash(opponent):
            if _BASELINE.fullmatch(opponent) is None:
                raise ProvenanceError(
                    f"{opponent!r} is neither a checkpoint id nor <name>@<commit>"
                )
            return Classification(SEEN, "a scripted baseline (C5)")
        theirs = [opponent] if isinstance(opponent, str) else list(opponent)
        self.ancestry(theirs)  # every opponent checkpoint needs a record (C7)
        ours = {candidate} if isinstance(candidate, str) else set(candidate)
        inside = sorted(set(theirs) & mine.checkpoints)
        if inside:
            return Classification(SEEN, f"{inside[0]} is in the candidate's ancestry")
        if any(self._records[o].exploiter_target in ours for o in theirs):
            return Classification(HELD_OUT, "an evaluation exploiter of the candidate (C3)")
        independence = self.independent(candidate, theirs)
        if independence.independent:
            return Classification(HELD_OUT, "an independent lineage (C6)")
        shared = (*independence.shared_checkpoints, *independence.shared_sources)
        return Classification(SEEN, f"a related lineage: shares {shared[0]} (C6)")
