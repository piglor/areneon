"""The C1/C6 checker (protocol C1-C3, C5-C7) on a synthetic provenance graph."""

from __future__ import annotations

import hashlib
import random
from dataclasses import replace
from typing import Any

import pytest
from areneon_ml.checkpoint.provenance import (
    HELD_OUT,
    SEEN,
    ProvenanceError,
    ProvenanceGraph,
)
from areneon_ml.checkpoint.record import CheckpointRecord

from .support import sample


def h(name: str) -> str:
    return hashlib.sha256(name.encode()).hexdigest()


MANIFEST: dict[str, Any] = sample("checkpoint-record/valid/battle.json")["manifest"]


def record(
    name: str,
    *,
    parent: str | None = None,
    league: tuple[str, ...] = (),
    target: str | None = None,
    sets: tuple[str, ...] = (),
) -> CheckpointRecord:
    return CheckpointRecord(
        checkpoint_id=h(name),
        role="battle",
        lineage_id=name,
        parent=None if parent is None else h(parent),
        league_opponents=tuple(sorted(h(o) for o in league)),
        exploiter_target=None if target is None else h(target),
        training_set_hashes=tuple(sorted(h(s) for s in sets)),
        team_set_manifest_hash=h("teams"),
        run_config_hash=h("config"),
        learner_state_hash=h("state"),
        encoder_version="enc1:" + "e" * 64,
        data_class="synthetic",
        manifest=MANIFEST,
    )


# Lineage A: A0 -> A1 -> A2 -> A3. A0 and C0 both warm-start from the behaviour-cloning
# source `bc`. B0 -> B1 shares nothing. E is an evaluation exploiter of A2 that A3 later
# trains against.
RECORDS = [
    record("A0", sets=("bc", "s-a0")),
    record("A1", parent="A0", league=("A0",), sets=("s-a1",)),
    record("A2", parent="A1", league=("A0", "A1"), sets=("s-a2",)),
    record("A3", parent="A2", league=("E",), sets=("s-a3",)),
    record("B0", sets=("s-b0",)),
    record("B1", parent="B0", league=("B0",), sets=("s-b1",)),
    record("C0", sets=("bc", "s-c0")),
    record("E", league=("A2",), target="A2", sets=("s-e",)),
]
SOURCES: dict[str, list[str]] = {
    h("bc"): [],
    h("s-a0"): [],
    h("s-a1"): [h("A0")],
    h("s-a2"): [h("A1")],
    h("s-a3"): [h("A2")],
    h("s-b0"): [],
    h("s-b1"): [h("B0")],
    h("s-c0"): [],
    h("s-e"): [h("A2")],
}


def graph(
    records: list[CheckpointRecord] | None = None, sources: dict[str, list[str]] | None = None
) -> ProvenanceGraph:
    return ProvenanceGraph(
        RECORDS if records is None else records, SOURCES if sources is None else sources
    )


def test_the_ancestry_is_the_checkpoint_and_everything_it_came_from() -> None:
    a2 = graph().ancestry(h("A2"))
    assert a2.checkpoints == {h("A2"), h("A1"), h("A0")}
    assert a2.sources == {h("s-a2"), h("s-a1"), h("s-a0"), h("bc")}
    assert graph().ancestry(h("B0")).checkpoints == {h("B0")}
    # An exploiter has its target in its ancestry; the target does not have the exploiter.
    assert h("A2") in graph().ancestry(h("E")).checkpoints
    assert h("E") not in a2.checkpoints
    # Data generated by a checkpoint puts that checkpoint (and its past) in the ancestry.
    assert h("A0") in graph().ancestry(h("A1")).checkpoints


@pytest.mark.parametrize(
    ("a", "b", "independent"),
    [
        ("A2", "B1", True),
        ("B1", "A2", True),
        ("A2", "C0", False),  # the shared behaviour-cloning source
        ("A2", "A1", False),
        ("A2", "A2", False),
        ("A3", "B0", True),
        ("B1", "C0", True),
    ],
)
def test_c6_independence(a: str, b: str, independent: bool) -> None:
    found = graph().independent(h(a), h(b))
    assert found.independent is independent
    assert graph().independent(h(b), h(a)).independent is independent


def test_c6_names_what_is_shared() -> None:
    shared = graph().independent(h("A2"), h("C0"))
    assert shared.shared_sources == (h("bc"),)
    assert shared.shared_checkpoints == ()
    own = graph().independent(h("A2"), h("A1"))
    assert h("A1") in own.shared_checkpoints
    assert h("A0") in own.shared_checkpoints


@pytest.mark.parametrize(
    ("candidate", "opponent", "label", "reason"),
    [
        ("A2", "A1", SEEN, "in the candidate's ancestry"),
        ("A2", "A2", SEEN, "in the candidate's ancestry"),
        ("A2", "B1", HELD_OUT, "independent lineage"),
        ("A2", "C0", SEEN, "related lineage"),
        ("A2", "E", HELD_OUT, "exploiter of the candidate"),
        ("A3", "E", SEEN, "in the candidate's ancestry"),  # C3: seen once it joined a league
        ("A1", "A2", SEEN, "related lineage"),  # a later checkpoint of the own lineage
        ("B1", "E", HELD_OUT, "independent lineage"),  # an exploiter of someone else's candidate
        ("A2", "first-legal@golden", SEEN, "scripted baseline"),
        ("B1", "random-legal@4f9e295", SEEN, "scripted baseline"),
    ],
)
def test_c1_seen_or_held_out(candidate: str, opponent: str, label: str, reason: str) -> None:
    found = graph().classify(h(candidate), opponent if "@" in opponent else h(opponent))
    assert found.label == label
    assert reason in found.reason


def test_a_pair_is_classified_as_a_whole() -> None:
    records = [
        replace(record("Ap", sets=("s-ap",)), role="preview"),
        record("Ab", sets=("s-ab",)),
        replace(record("Bp", sets=("s-bp",)), role="preview"),
        record("Bb", sets=("s-bb",)),
        replace(record("Cp", sets=("s-cp",)), role="preview"),
        record("Cb", parent="Ab", sets=("s-cb",)),  # the Battle half descends from A's
    ]
    sources: dict[str, list[str]] = {
        h(s): [] for s in ("s-ap", "s-ab", "s-bp", "s-bb", "s-cp", "s-cb")
    }
    pairs = graph(records, sources)
    candidate = (h("Ap"), h("Ab"))
    assert pairs.classify(candidate, (h("Bp"), h("Bb"))).label == HELD_OUT
    mixed = pairs.classify(candidate, (h("Cp"), h("Cb")))
    assert mixed.label == SEEN  # one related half makes the pair related
    assert "related lineage" in mixed.reason
    assert pairs.classify(candidate, (h("Ap"), h("Bb"))).label == SEEN
    assert pairs.independent(candidate, (h("Bp"), h("Bb"))).independent


def test_the_answer_does_not_depend_on_the_order_of_the_records() -> None:
    shuffled = RECORDS[:]
    random.Random(7).shuffle(shuffled)
    for a, b in [("A2", "B1"), ("A2", "C0"), ("A2", "E"), ("A3", "E")]:
        assert graph(shuffled).classify(h(a), h(b)) == graph().classify(h(a), h(b))


def test_a_long_lineage_does_not_overflow_the_stack() -> None:
    chain = [record("g0", sets=("s0",))]
    sources: dict[str, list[str]] = {h("s0"): []}
    for number in range(1, 1500):
        chain.append(record(f"g{number}", parent=f"g{number - 1}", sets=(f"s{number}",)))
        sources[h(f"s{number}")] = [h(f"g{number - 1}")]
    long = graph(chain, sources)
    assert len(long.ancestry(h("g1499")).checkpoints) == 1500


# -- negative controls: a graph that cannot support a classification ----------------------


def refused(
    match: str, records: list[CheckpointRecord], sources: dict[str, list[str]] | None = None
) -> None:
    with pytest.raises(ProvenanceError, match=match):
        ProvenanceGraph(records, {} if sources is None else sources)


def test_a_referenced_checkpoint_without_a_record_is_refused() -> None:
    refused("parent of .* has no record", [record("X", parent="missing")])
    refused("league opponent of", [record("X", league=("missing",))])
    refused("exploiter target of", [record("X", target="missing")])
    refused("generator of data source", [record("X")], {h("s"): [h("missing")]})


def test_a_training_set_missing_from_the_registry_is_refused() -> None:
    refused("not in the sources registry", [record("X", sets=("unlisted",))])


def test_a_bad_registry_is_refused() -> None:
    refused("not a SHA-256 hash", [record("X")], {"nothex": []})
    refused("sorted unique ids", [record("X")], {h("s"): [h("a"), h("b")]})  # h("b") sorts first
    refused("sorted unique ids", [record("X")], {h("s"): ["nothex"]})


def test_two_records_for_one_checkpoint_are_refused() -> None:
    refused("has two records", [record("X"), record("X")])


def test_a_cycle_is_refused() -> None:
    refused("cycle", [record("X", parent="Y"), record("Y", parent="X")])
    three = [record("X", parent="Y"), record("Y", parent="Z"), record("Z", parent="X")]
    refused("cycle", three)
    two = [record("X", sets=("s",)), record("Y", parent="X")]
    refused("cycle", two, {h("s"): [h("Y")]})  # data generated by a descendant


def test_c3_an_exploiter_in_its_targets_league_is_refused() -> None:
    bad = [record("K", league=("E",)), record("E", target="K")]
    refused("C3", bad)


def test_the_questions_are_checked_too() -> None:
    g = graph()
    with pytest.raises(ProvenanceError, match="has no record"):
        g.classify(h("unknown"), h("A1"))
    with pytest.raises(ProvenanceError, match="has no record"):
        g.classify(h("A2"), h("unknown"))
    with pytest.raises(ProvenanceError, match="neither a checkpoint id nor"):
        g.classify(h("A2"), "Not A Baseline")
    with pytest.raises(ProvenanceError, match="no checkpoint given"):
        g.ancestry([])
    with pytest.raises(ProvenanceError, match="has no record"):
        g.independent(h("A2"), h("unknown"))


def test_a_pair_is_held_out_only_if_every_member_qualifies() -> None:
    mixed = graph().classify((h("A2"),), (h("E"), h("C0")))  # an exploiter and a related lineage
    assert mixed.label == SEEN
    assert h("C0") in mixed.reason
    both = graph().classify(
        (h("A2"),), (h("E"), h("B1"))
    )  # an exploiter and an independent lineage
    assert both.label == HELD_OUT
    assert "exploiters" in both.reason
    assert graph().classify((h("A2"),), (h("E"),)).label == HELD_OUT
    assert graph().classify((h("A2"),), (h("B1"), h("B0"))).label == HELD_OUT
    assert graph().classify((h("A2"),), (h("B1"), h("A1"))).label == SEEN


def test_records_must_agree_with_each_other() -> None:
    base = [record("P", sets=("s",)), record("K", parent="P")]
    sources: dict[str, list[str]] = {h("s"): []}
    ProvenanceGraph(base, sources)  # consistent
    other_encoder = replace(base[0], encoder_version="enc2:" + "e" * 64)
    refused("differ in encoder_version", [other_encoder, base[1]], sources)
    preview_parent = replace(base[0], role="preview")
    refused(r"\(battle\) has parent .* \(preview\)", [preview_parent, base[1]], sources)
    # Either half of a frozen pair may be an opponent or an exploiter target.
    other_half = replace(record("O"), role="preview")
    ProvenanceGraph([other_half, record("K", league=("O",))], {})
    ProvenanceGraph([other_half, record("K", target="O")], {})
    private = replace(base[0], data_class="private")
    refused("descends from private", [private, base[1]], sources)
    refused("descends from private", [private, record("K", league=("P",))], sources)
    generated = [replace(record("G"), data_class="private"), record("K", sets=("s",))]
    refused("descends from private", generated, {h("s"): [h("G")]})
    both_private = replace(base[1], data_class="private")
    ProvenanceGraph([private, both_private], sources)  # private may descend from private
